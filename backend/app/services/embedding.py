"""Durable M4 orchestration: embed an active chunk dataset, stage it, verify it, then activate.

The shape mirrors M2 and M3 — a fenced lease, the transactional outbox, one atomic commit of
durable state — with one addition that matters: the vector index is a second system that offers no
cross-store transaction. Correctness therefore rests on three properties rather than on a
distributed commit:

* deterministic point identity, so a replayed batch overwrites instead of duplicating;
* read-back reconciliation against the expected set recorded in PostgreSQL;
* activation as a PostgreSQL state change that happens only after that reconciliation, leaving the
  previous active index untouched when a replacement fails.
"""

